import fs from 'node:fs/promises';
import {Workbook,SpreadsheetFile} from '@oai/artifact-tool';
const root=new URL('../',import.meta.url);
const plan=JSON.parse(await fs.readFile(new URL('brandboom-restore-plan.json',root),'utf8'));
const book=Workbook.create(),sheet=book.worksheets.add('Products');
sheet.getRange('A1:S177').format={font:{name:'Calibri',size:11},wrapText:true,verticalAlignment:'top',columnWidth:18};
sheet.getRange('A1:S1').values=[plan.headers];sheet.getRange('A2:S177').values=plan.rows;
sheet.getRange('A1:S1').format={fill:'#35533B',font:{name:'Calibri',size:11,bold:true,color:'#FFFFFF'},rowHeight:40};
sheet.getRange('A2:S177').format.rowHeight=280;
sheet.getRange('E1:E177').format.columnWidth=48;sheet.getRange('F1:F177').format.columnWidth=80;
sheet.getRange('G1:G177').format.columnWidth=34;sheet.getRange('H2:I177').format.numberFormat='0.00';
sheet.getRange('P2:Q177').format.numberFormat='0';sheet.getRange('R1:R177').format.columnWidth=60;
book.recalculate();const read=sheet.getRange('A2:S177').values;
for(let i=0;i<176;i++)for(let j=0;j<19;j++)if((read[i][j]??null)!==(plan.rows[i][j]??null))throw Error(`Changed cell ${i+2}:${j+1}`);
if(new Set(read.map(r=>r[0])).size!==176)throw Error('Duplicate SKU');
const preview=await book.render({sheetName:'Products',range:'E1:H3',scale:1,format:'png'});
await fs.writeFile(new URL('brandboom-restore-preview.png',root),new Uint8Array(await preview.arrayBuffer()));
await(await SpreadsheetFile.exportXlsx(book)).save(new URL('brandboom-restore-176.xlsx',root).pathname);
console.log(JSON.stringify({status:'AUTHORED_VALUES_VERIFIED',products:176,columns:19,internal_costs_exported:false}));
