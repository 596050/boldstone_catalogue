import fs from 'node:fs/promises';
import path from 'node:path';
import {Workbook,SpreadsheetFile} from '@oai/artifact-tool';
const out=path.dirname(new URL(import.meta.url).pathname);
const plan=JSON.parse(await fs.readFile(path.join(out,'upload-plan.json'),'utf8'));
const book=Workbook.create();const sheet=book.worksheets.add('Products');
sheet.getRange('A1:R177').format={font:{name:'Calibri',size:11},wrapText:true,verticalAlignment:'top',columnWidth:18};
sheet.getRange('A1:R1').values=[plan.headers];sheet.getRange('A2:R177').values=plan.rows;
sheet.getRange('A1:R1').format={fill:'#35533B',font:{name:'Calibri',size:11,bold:true,color:'#FFFFFF'},rowHeight:38};
sheet.getRange('A2:R177').format.rowHeight=320;
sheet.getRange('A1:D177').format.columnWidth=24;
sheet.getRange('E1:E177').format.columnWidth=48;sheet.getRange('F1:F177').format.columnWidth=80;
sheet.getRange('G1:G177').format.columnWidth=35;sheet.getRange('H2:I177').format.numberFormat='0.00';
sheet.getRange('P2:Q177').format.numberFormat='0';sheet.getRange('R1:R177').format.columnWidth=60;
await book.recalculate();
const readback=sheet.getRange('A2:R177').values;
for(let i=0;i<plan.rows.length;i++)for(let j=0;j<18;j++)if((readback[i][j]??null)!==(plan.rows[i][j]??null))throw Error(`Mismatch row ${i+2} column ${j+1}`);
if(new Set(readback.map(r=>r[0])).size!==176)throw Error('Duplicate SKUs');
const preview=await book.render({sheetName:'Products',range:'E1:H4',scale:1,format:'png'});
await fs.writeFile(path.join(out,'preview.png'),new Uint8Array(await preview.arrayBuffer()));
await (await SpreadsheetFile.exportXlsx(book)).save(path.join(out,'boldstone_brandboom_products.xlsx'));
console.log(JSON.stringify({status:'AUTHORED_AND_VALUE_VERIFIED',products:readback.length,public_columns:18,internal_costs_exported:false}));
